export const STATUS = {
  DRAFT: 'DRAFT',
  SUBMITTED: 'SUBMITTED',
  UNDER_REVIEW: 'UNDER_REVIEW',
  ACTION_REQUIRED: 'ACTION_REQUIRED',
  VERIFIED: 'VERIFIED',
  SHORTLISTED: 'SHORTLISTED',
  ADMITTED: 'ADMITTED',
  REJECTED: 'REJECTED',
  WITHDRAWN: 'WITHDRAWN',
};

export const STATUS_VALUES = Object.values(STATUS);

/** Legal transitions. Anything not listed here is a 400, never a silent no-op. */
export const STATUS_TRANSITIONS = {
  DRAFT: [STATUS.SUBMITTED, STATUS.WITHDRAWN],
  SUBMITTED: [STATUS.UNDER_REVIEW, STATUS.WITHDRAWN, STATUS.REJECTED],
  UNDER_REVIEW: [STATUS.ACTION_REQUIRED, STATUS.VERIFIED, STATUS.REJECTED, STATUS.WITHDRAWN],
  ACTION_REQUIRED: [STATUS.UNDER_REVIEW, STATUS.WITHDRAWN, STATUS.REJECTED],
  VERIFIED: [STATUS.SHORTLISTED, STATUS.REJECTED, STATUS.WITHDRAWN],
  SHORTLISTED: [STATUS.ADMITTED, STATUS.REJECTED, STATUS.WITHDRAWN],
  ADMITTED: [],
  REJECTED: [],
  WITHDRAWN: [],
};

export const canTransition = (from, to) => (STATUS_TRANSITIONS[from] || []).includes(to);

/** Transitions the applicant may trigger themselves. */
export const APPLICANT_TRANSITIONS = [STATUS.SUBMITTED, STATUS.WITHDRAWN];

export const EDITABLE_STATUSES = [STATUS.DRAFT, STATUS.ACTION_REQUIRED];

export default STATUS;
